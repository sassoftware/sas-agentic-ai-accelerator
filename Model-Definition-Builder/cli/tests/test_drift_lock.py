"""The lockfile's manifest hash must not depend on the contributor's OS: a
Windows checkout reads definition.yaml with CRLF, Linux and CI with LF, and a
raw hash re-stamped every lock file whenever the other platform regenerated."""
import hashlib
import json

from mdb.core import drift


def test_manifest_hash_is_the_same_for_crlf_and_lf_checkouts(tmp_path):
    lf = b"schema: 1\nkind: llm\nmodel_id: x\n"
    crlf = lf.replace(b"\n", b"\r\n")
    files = {"options.json": b"{}\n"}

    drift.write_lock(tmp_path, lf, files)
    from_lf = json.loads((tmp_path / drift.LOCK_FILENAME).read_text(encoding="utf-8"))
    drift.write_lock(tmp_path, crlf, files)
    from_crlf = json.loads((tmp_path / drift.LOCK_FILENAME).read_text(encoding="utf-8"))

    assert from_lf["manifest_sha256"] == from_crlf["manifest_sha256"]
    # ...and it is the hash of the canonical (LF) bytes, i.e. what CI computes.
    assert from_lf["manifest_sha256"] == hashlib.sha256(lf).hexdigest()
    assert from_lf["files"] == from_crlf["files"] == {"options.json": hashlib.sha256(b"{}\n").hexdigest()}


# The first line of a score file names the mdb that rendered it. A new release
# of mdb renders the same file with another version in that line only, and
# that is no drift: before, every definition of a site was stale (V004, an
# error) after an upgrade of mdb.
def _score(version: str, body: bytes = b"print('x')\n") -> bytes:
    return (f"# GENERATED by mdb {version} from definition.yaml - edit definition.yaml and run "
            f"'mdb generate x' instead of editing this file.\n").encode() + body


def _status(folder, rendered):
    return {c.filename: c.status for c in drift.classify(folder, rendered)}


def test_a_file_that_differs_only_in_the_version_of_mdb_is_unchanged(tmp_path):
    (tmp_path / "xScore.py").write_bytes(_score("2.2.0"))
    drift.write_lock(tmp_path, b"m\n", {"xScore.py": _score("2.2.0")})

    assert _status(tmp_path, {"xScore.py": _score("9.9.9")}) == {"xScore.py": drift.FileStatus.UNCHANGED}


def test_a_lock_written_before_keeps_telling_stale_from_hand_edited(tmp_path):
    # a lock of an earlier release: the hash of the file as written, stamp included
    (tmp_path / "xScore.py").write_bytes(_score("2.2.0"))
    (tmp_path / drift.LOCK_FILENAME).write_text(json.dumps({
        "generator": "mdb 2.2.0", "manifest_sha256": "0",
        "files": {"xScore.py": hashlib.sha256(_score("2.2.0")).hexdigest()}}), encoding="utf-8")
    template_changed = {"xScore.py": _score("9.9.9", b"print('y')\n")}
    assert _status(tmp_path, template_changed) == {"xScore.py": drift.FileStatus.STALE}

    (tmp_path / "xScore.py").write_bytes(_score("2.2.0", b"print('mine')\n"))
    assert _status(tmp_path, template_changed) == {"xScore.py": drift.FileStatus.HAND_EDITED}


def test_a_lock_written_now_matches_a_file_that_kept_an_earlier_stamp(tmp_path):
    # generate left the file alone (unchanged but for the version) and wrote the lock
    (tmp_path / "xScore.py").write_bytes(_score("2.2.0"))
    drift.write_lock(tmp_path, b"m\n", {"xScore.py": _score("9.9.9")})

    template_changed = {"xScore.py": _score("9.9.9", b"print('y')\n")}
    assert _status(tmp_path, template_changed) == {"xScore.py": drift.FileStatus.STALE}


def test_only_the_first_line_is_the_stamp(tmp_path):
    body = b"x = 1\n# GENERATED by mdb 2.2.0 from definition.yaml\n"
    (tmp_path / "xScore.py").write_bytes(_score("2.2.0", body))
    drift.write_lock(tmp_path, b"m\n", {"xScore.py": _score("2.2.0", body)})

    other = body.replace(b"2.2.0", b"9.9.9")
    assert _status(tmp_path, {"xScore.py": _score("9.9.9", other)}) == {"xScore.py": drift.FileStatus.STALE}


def test_a_new_version_of_mdb_alone_rewrites_no_lock_file(tmp_path):
    files = {"xScore.py": _score("2.2.0"), "options.json": b"{}\n"}
    drift.write_lock(tmp_path, b"m\n", files)
    lock = tmp_path / drift.LOCK_FILENAME
    lock.write_text(lock.read_text(encoding="utf-8").replace(f"mdb {drift.__version__}", "mdb 0.0.1"),
                    encoding="utf-8")
    before = lock.read_bytes()

    drift.write_lock(tmp_path, b"m\n", {**files, "xScore.py": _score("9.9.9")})
    assert lock.read_bytes() == before

    drift.write_lock(tmp_path, b"changed\n", files)
    assert json.loads(lock.read_text(encoding="utf-8"))["generator"] == f"mdb {drift.__version__}"
